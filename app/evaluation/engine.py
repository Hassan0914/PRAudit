"""AI Evaluation Engine measuring AI review precision, recall, latency, and false positive rates."""

from typing import List, Set
from app.core.logging import setup_logger
from app.evaluation.models import EvaluationMetric, EvaluationReport
from app.review.review_models import ReviewFinding, ReviewReport

logger = setup_logger("evaluation.engine")


class AIEvaluationEngine:
    """Engine measuring AI review quality, latency, token consumption, and precision/recall."""

    def evaluate_ai_review(
        self,
        review_id: str,
        ai_finding_titles: List[str],
        ground_truth_findings: List[ReviewFinding],
        latency_ms: float = 120.0,
        total_tokens: int = 1500,
    ) -> EvaluationReport:
        """Evaluate AI findings against deterministic ground-truth findings.

        Args:
            review_id: Target review ID.
            ai_finding_titles: List of titles generated by AI.
            ground_truth_findings: List of ground-truth ReviewFinding objects from deterministic rules.
            latency_ms: Execution latency in milliseconds.
            total_tokens: Total tokens consumed.

        Returns:
            EvaluationReport containing precision, recall, and false positive metrics.
        """
        gt_titles = {f.title.lower() for f in ground_truth_findings}
        ai_titles = {t.lower() for t in ai_finding_titles}

        true_positives = len(ai_titles.intersection(gt_titles))
        false_positives = len(ai_titles - gt_titles)
        false_negatives = len(gt_titles - ai_titles)

        precision = (
            true_positives / (true_positives + false_positives)
            if (true_positives + false_positives) > 0
            else 1.0
        )
        recall = (
            true_positives / (true_positives + false_negatives)
            if (true_positives + false_negatives) > 0
            else 1.0
        )

        # Token efficiency score (higher is better, benchmark target 2000 tokens)
        token_eff = max(0.0, min(100.0, (1.0 - (total_tokens / 10000.0)) * 100.0))

        metrics = [
            EvaluationMetric(name="Precision", value=round(precision, 4), target_benchmark=0.85, status="PASSED" if precision >= 0.85 else "WARNING"),
            EvaluationMetric(name="Recall", value=round(recall, 4), target_benchmark=0.80, status="PASSED" if recall >= 0.80 else "WARNING"),
            EvaluationMetric(name="Latency (ms)", value=round(latency_ms, 2), target_benchmark=1000.0, status="PASSED" if latency_ms <= 1000 else "WARNING"),
            EvaluationMetric(name="Token Efficiency", value=round(token_eff, 2), target_benchmark=70.0, status="PASSED" if token_eff >= 70.0 else "WARNING"),
        ]

        logger.info(
            "Evaluation complete for review %s: Precision=%.2f, Recall=%.2f, FP=%d, FN=%d",
            review_id,
            precision,
            recall,
            false_positives,
            false_negatives,
        )

        return EvaluationReport(
            review_id=review_id,
            precision=round(precision, 4),
            recall=round(recall, 4),
            false_positives_count=false_positives,
            false_negatives_count=false_negatives,
            latency_ms=round(latency_ms, 2),
            token_efficiency_score=round(token_eff, 2),
            metrics=metrics,
        )
